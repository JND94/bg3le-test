#!/usr/bin/env python3
# Writes src/vendor/system_names.inc: bg3se's ExtSystemType labels, the engine
# class each names, and the C++ class bg3se declares for it (the name its field
# table is under), from the DEFINE_SYSTEM lines in the vendored headers
# (bg3se, by Norbyte and the bg3se contributors).
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
defs = root / "vendor/bg3se/BG3Extender/GameDefinitions"
system = re.compile(r'DEFINE_SYSTEM\((\w+),\s*"([^"]+)"\)')
struct = re.compile(r'^\s*(?:struct|class)\s+(?:\[\[[^\]]*\]\]\s*)?(\w+)\b[^;]*$')
begin_ns = re.compile(r'^\s*BEGIN_NS\(([\w:]+)\)')
begin_se = re.compile(r'^\s*BEGIN_SE\(\)')
end_ns = re.compile(r'^\s*END_(?:NS|SE)\(\)')

rows = {}
for header in sorted(defs.rglob("*.h")):
    ns, last = [], None
    for line in header.read_text(errors="replace").splitlines():
        if m := begin_ns.match(line):
            ns.append(m.group(1))
        elif begin_se.match(line):
            ns.append("")
        elif end_ns.match(line) and ns:
            ns.pop()
        elif m := struct.match(line):
            last = m.group(1)
        elif m := system.search(line):
            label, engine = m.groups()
            scope = ns[-1] if ns else ""
            cls = f"{scope}::{last}" if scope else last
            rows.setdefault(label, (engine, cls))

# The classes the field tables cover; a system bg3se declares no fields for
# keeps its engine name.
props = (defs / "Generated/PropertyMaps.inl").read_text(errors="replace")
described = set(re.findall(r'BEGIN_CLS\(([^,]+),', props))

out = root / "src/vendor/system_names.inc"
lines = ["// Generated by tools/gen-system-names.py; do not edit."]
for label, (engine, cls) in sorted(rows.items()):
    lines.append(f'{{"{label}", "{engine}", "{cls if cls in described else engine}"}},')
out.write_text("\n".join(lines) + "\n")
renamed = sum(1 for engine, cls in rows.values() if cls in described and cls != engine)
print(f"{len(rows)} systems ({renamed} under another C++ name) -> {out.relative_to(root)}")
